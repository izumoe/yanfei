"""Original periodic waves: five banks x four waves x four harmonic limits = 40 KiB.

The vintage banks evoke broad timbral families, using our own harmonic recipes.
No ROM data, recordings or proprietary tables are used. Floating point is offline
only; runtime reads fixed-point flash tables with no allocation.
"""
import math
from pathlib import Path

CAPS = (32, 8, 2, 1)
BANKS = (
    ("BASIC", ("sine", "triangle", "square", "saw")),
    ("COLOR", ("hollow", "glass", "octaves", "bright glass")),
    ("PPG", ("nasal", "comb", "vocal", "metal")),
    ("ESQ", ("bass", "reed", "keys", "hollow reed")),
    ("VS", ("airy", "glass", "brass", "shimmer")),
)


def peak(k, centre, width):
    return math.exp(-((k - centre) / width) ** 2)


def weight(w, k):
    # Original BASIC/COLOR recipes stay byte-identical for existing patches.
    if w == 0:
        return 1.0 if k == 1 else 0.0
    if w == 1:
        return (1 if k % 4 == 1 else -1) / k**2 if k % 2 else 0.0
    if w == 2:
        return 1 / k if k % 2 else 0.0
    if w == 3:
        return (-1)**(k + 1) / k
    if w == 4:
        return math.cos(k * math.pi / 3) / k
    if w == 5:
        return math.exp(-((k - 5) / 2)**2) / k + (.4 if k == 1 else 0)
    if w == 6:
        return (1 if k in (1, 2, 4, 8) else 0) / k
    if w == 7:
        return math.exp(-((k - 9) / 3)**2) / k + (.25 if k == 1 else 0)
    # PPG-inspired: prominent upper harmonics, comb notches and moving formants.
    if w == 8:
        return (1 if k == 1 else 0) + (1.2 * peak(k, 3, 1.3) + .8 * peak(k, 9, 2)) / math.sqrt(k)
    if w == 9:
        return (1 if k % 3 else -.4) * math.exp(-(k / 24)**2) / math.sqrt(k)
    if w == 10:
        return (.6 if k == 1 else 0) + (1.4 * peak(k, 2, .9) + 2 * peak(k, 7, 1.5) + peak(k, 12, 2)) / k
    if w == 11:
        return (.5 if k == 1 else 0) + (peak(k, 7, 1) - .9 * peak(k, 11, 1.2) + .7 * peak(k, 17, 1.5)) / math.sqrt(k)
    # ESQ-inspired hybrid voices: sustained bass/reed/key spectra, not samples.
    if w == 12:
        return (1 if k == 1 else (.35 / k**1.3 if k % 2 else .16 / k**1.8))
    if w == 13:
        return math.exp(-(k / 14)**2) / k if k % 2 else (.15 if k == 2 else 0)
    if w == 14:
        return {1: 1, 2: .32, 3: .17, 4: .18, 6: .05, 7: .08, 10: .03}.get(k, 0)
    if w == 15:
        return (1 / k if k % 2 else 0) + (.2 if k == 2 else 0) + .3 * peak(k, 7, 1.5)
    # Prophet VS-inspired corners: airy, glassy, brass-like and shimmering spectra.
    # POS still follows a linear path through the corners, not a vector mixer.
    if w == 16:
        return 1 if k == 1 else .38 / k**2
    if w == 17:
        return {1: 1, 2: .45, 5: .25, 9: .12}.get(k, 0)
    if w == 18:
        return (1 if k % 2 else .65) * math.exp(-(k / 18)**2) / k
    if w == 19:
        return (.65 if k == 1 else 0) + (.8 * peak(k, 8, 2) + .5 * peak(k, 15, 3)) / k**.6
    raise ValueError(f"unknown waveform {w}")


def tables():
    waves = []
    for w in range(len(BANKS) * 4):
        levels = []
        for cap in CAPS:
            vals = [sum(weight(w, k) * math.sin(2 * math.pi * k * i / 256)
                        for k in range(1, cap + 1)) for i in range(256)]
            normal = max(max(abs(v) for v in vals), 1e-9)
            levels.append([round(v / normal * 28000) for v in vals])
        waves.append(levels)
    return waves


def generate():
    count = len(BANKS) * 4
    out = ["/* SPDX-License-Identifier: MIT */",
           f"/* Generated by tools/gen_wave_bank.py: {count} x 4 x 256 x int16 = {count * 2048} bytes. */",
           f"#define WAVE_NBANKS {len(BANKS)}u",
           "#define WAVE_WAVES_PER_BANK 4u",
           'static const char *const WAVE_BANK_NAMES[] = {' + ','.join(f'"{b[0]}"' for b in BANKS) + '};',
           f"static const int16_t WAVE_BANK[{count}][4][256] = {{"]
    for w, levels in enumerate(tables()):
        out.append('{ /* ' + BANKS[w // 4][0] + ': ' + BANKS[w // 4][1][w % 4] + ' */')
        out.extend('{' + ','.join(str(v) for v in samples) + '},' for samples in levels)
        out.append('},')
    out.append('};\n')
    return '\n'.join(out)


if __name__ == '__main__':
    Path(__file__).resolve().parents[1].joinpath('src/wave_bank.h').write_text(generate())
